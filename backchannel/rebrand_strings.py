#!/usr/bin/env python3
"""Generate Backchannel's string overlay from Molly's strings.

Molly's strings say "Molly" in place of "Signal". Rather than editing
Molly's string files (which change in every upstream merge), this writes
copies of just those strings, with "Molly" replaced by "Backchannel", into
the prod flavor's resources, which override main's at build time.

Run from the repo root after every Molly merge:
    python3 backchannel/rebrand_strings.py
"""
import pathlib
import re
import sys

APP_TITLE = "Backchannel"
ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "app/src/prod/res"
OUT_NAME = "strings_backchannel.xml"
# App first: app resources win over library resources with the same name.
SOURCE_RES = [ROOT / "app/src/main/res"] + sorted((ROOT / "feature").glob("*/src/main/res"))

# "Molly" as a word. Leaves MollySocket and molly.im alone.
WORD = re.compile(r"\bMolly\b")
ELEMENT = re.compile(
    r"<(string|plurals)\b([^>]*?)\bname=\"([^\"]+)\"([^>]*)>(.*?)</\1>", re.S
)
ROOT_TAG = re.compile(r"<resources\b[^>]*>")


def overlay_for(values_dir_name):
    entries = {}
    root_tag = "<resources>"
    for res in SOURCE_RES:
        d = res / values_dir_name
        if not d.is_dir():
            continue
        for f in sorted(d.glob("strings*.xml")):
            text = f.read_text(encoding="utf-8")
            m = ROOT_TAG.search(text)
            if m and "xmlns" in m.group(0) and root_tag == "<resources>":
                root_tag = m.group(0)
            for el in ELEMENT.finditer(text):
                tag, pre, name, post, body = el.groups()
                if name in entries or not WORD.search(body):
                    continue
                attrs = (pre + post).replace('mollyify="true"', "")
                attrs = re.sub(r"\s+", " ", attrs).strip()
                attrs = (" " + attrs) if attrs else ""
                new_body = WORD.sub(APP_TITLE, body)
                entries[name] = f'  <{tag} name="{name}"{attrs}>{new_body}</{tag}>'
    return root_tag, entries


def main():
    dirs = set()
    for res in SOURCE_RES:
        dirs.update(p.name for p in res.glob("values*") if p.is_dir())
    written = 0
    for old in OUT_DIR.glob(f"values*/{OUT_NAME}"):
        old.unlink()
    for name in sorted(dirs):
        root_tag, entries = overlay_for(name)
        if not entries:
            continue
        out = OUT_DIR / name / OUT_NAME
        out.parent.mkdir(parents=True, exist_ok=True)
        lines = ['<?xml version="1.0" encoding="utf-8"?>',
                 "<!-- BACKCHANNEL: generated by backchannel/rebrand_strings.py. Don't edit. -->",
                 root_tag]
        lines += [entries[k] for k in sorted(entries)]
        lines.append("</resources>")
        out.write_text("\n".join(lines) + "\n", encoding="utf-8")
        written += len(entries)
    for d in OUT_DIR.glob("values*"):
        if d.is_dir() and not any(d.iterdir()):
            d.rmdir()
    print(f"wrote {written} strings")


if __name__ == "__main__":
    sys.exit(main())
